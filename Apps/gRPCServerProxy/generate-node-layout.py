#!/usr/bin/env python3
"""Writes NodeLayout.swift: the field tables of the history node of Draw Things.

    python3 generate-node-layout.py

The proxy reads and rebuilds a TensorHistoryNode (a FlatBuffers table) field by field. For that it
has to know the kind of every slot, which the compiled blob does not say. The kinds come from
Libraries/History/Sources/tensor_history.fbs. When that schema gets new fields, run this script
again and check the diff; until then the proxy refuses to touch a node that has more slots than
this table knows (HistoryCorrector.Failure.unknownFields), so no field can get lost.
"""
import os
import re
import sys

here = os.path.dirname(os.path.abspath(__file__))
schema_path = os.path.join(here, "..", "..", "Libraries", "History", "Sources", "tensor_history.fbs")
schema = open(schema_path).read()
# The configuration of a request (config.fbs) has almost the same fields as the node; the proxy
# builds the node of a job from the configuration of its request.
config_path = os.path.join(here, "..", "..", "Libraries", "DataModels", "Sources", "config.fbs")
config_schema = open(config_path).read()

enums = dict(re.findall(r"enum (\w+)\s*:\s*(\w+)", schema))
enums.update(dict(re.findall(r"enum (\w+)\s*:\s*(\w+)", config_schema)))
SCALARS = {
    "bool": 1, "byte": 1, "ubyte": 1, "short": 2, "ushort": 2, "int": 4, "uint": 4,
    "long": 8, "ulong": 8, "float": 4, "double": 8,
}


def fields_of(table, source=None):
    source = source or schema
    body = source[source.index("table " + table):]
    body = body[body.index("{") + 1:body.index("}")]
    result = []
    for line in body.split(";"):
        m = re.match(r"\s*(\w+)\s*:\s*(\[?\w+\]?)\s*(?:=\s*[^;(]+?)?\s*(?:\(.*\))?\s*$", line.strip())
        if m:
            result.append((m.group(1), m.group(2)))
    return result


def kind(type_name):
    base = enums.get(type_name, type_name)
    if base in SCALARS:
        return ".scalar(%d)" % SCALARS[base]
    if base == "string":
        return ".string"
    if base == "[ubyte]":
        return ".bytes"
    if base == "[string]":
        return ".strings"
    m = re.match(r"\[(\w+)\]$", base)
    if m and m.group(1) in ("Control", "LoRA"):
        return ".tables(.%s)" % m.group(1).lower()
    sys.exit("unknown field type %r in tensor_history.fbs: extend generate-node-layout.py" % type_name)


out = [
    "// Generated by generate-node-layout.py from Libraries/History/Sources/tensor_history.fbs and",
    "// Libraries/DataModels/Sources/config.fbs.",
    "// Do not edit; run the script again when the schema changes.",
    "",
    "enum NodeKind {",
    "  case scalar(Int)  // Size in bytes.",
    "  case string",
    "  case bytes  // [ubyte]",
    "  case strings  // [string]",
    "  case tables(NodeTableType)",
    "}",
    "",
    "enum NodeTableType { case node, control, lora, configuration }",
    "",
    "struct NodeField {",
    "  let name: String",
    "  let kind: NodeKind",
    "}",
    "",
    "enum NodeLayout {",
]
for swift_name, table, source in (
    ("node", "TensorHistoryNode", schema), ("control", "Control", schema), ("lora", "LoRA", schema),
    ("configuration", "GenerationConfiguration", config_schema),
):
    out.append("  /// Slot i of the table is element i.")
    out.append("  static let %s: [NodeField] = [" % swift_name)
    for name, type_name in fields_of(table, source):
        out.append('    NodeField(name: "%s", kind: %s),' % (name, kind(type_name)))
    out.append("  ]")
    out.append("")
out[-1] = "}"
open(os.path.join(here, "NodeLayout.swift"), "w").write("\n".join(out) + "\n")
print("NodeLayout.swift: %d fields in TensorHistoryNode" % len(fields_of("TensorHistoryNode")))
