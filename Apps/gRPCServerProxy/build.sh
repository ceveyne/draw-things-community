#!/bin/bash
# Build and sign gRPCServerProxy (slim). Normally called by Apps/gRPCServerManager/build.sh, which
# puts the result into the app bundle; it can be run alone as well.
#
#   ./build.sh                   dev build: Developer ID signed, no hardened runtime
#   RELEASE=1 ./build.sh         hardened runtime and secure timestamp
#   NOTARIZE=1 RELEASE=1 ./build.sh   additionally notarized on its own (not needed in the bundle:
#                                the app is notarized once, with the proxy inside)
#   SKIP_BUILD=1 ./build.sh      only strip and sign what the last build left
#
# Environment:
#   CODESIGN_IDENTITY   name of the Developer ID Application certificate (required)
#   NOTARY_PROFILE      notarytool keychain profile, or APPLE_ID + APPLE_APP_SPECIFIC_PASSWORD + APPLE_TEAM_ID
#
# Run it as your own user, not with sudo.
#
# The binary is much smaller than a plain release build (155 MB):
#  1. The tokenizer tables of BinaryResources (about 58 MB) are replaced by empty stubs; the
#     proxy never tokenizes, only the certificates are kept.
#  2. The local symbols are stripped (about 23 MB).
# The slim build has its own build folder (.build-slim) and does not touch .build.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
PRODUCT="gRPCServerProxy"
BUILD_DIR="$SCRIPT_DIR/build"
OUTPUT="$BUILD_DIR/$PRODUCT"
SCRATCH="$REPO_ROOT/.build-slim"
RESOURCES="$REPO_ROOT/Libraries/BinaryResources/GeneratedC"
# Resources that are kept: the .c files of these are linked as they are.
KEEP="server_crt server_key root_ca isrgrootx1"
IDENTIFIER="com.satin-island.grpc-server-proxy"
RELEASE="${RELEASE:-0}"
NOTARIZE="${NOTARIZE:-0}"

RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'; NC='\033[0m'

cd "$REPO_ROOT"
echo -e "${GREEN}=== $PRODUCT Build ===${NC}"

if [ "$(id -u)" = "0" ]; then
    echo -e "${RED}Do not run this script with sudo: the Developer ID of the user is not visible then.${NC}" >&2
    exit 1
fi

SIGN_ID="${CODESIGN_IDENTITY:-}"
if [ -z "$SIGN_ID" ]; then
    echo -e "${RED}CODESIGN_IDENTITY is not set (name of your 'Developer ID Application' certificate).${NC}" >&2
    echo "  security find-identity -v -p codesigning" >&2
    exit 1
fi

NOTARY_ARGS=()
if [ "$NOTARIZE" = "1" ]; then
    if [ -n "${NOTARY_PROFILE:-}" ]; then
        NOTARY_ARGS=(--keychain-profile "$NOTARY_PROFILE")
    elif [ -n "${APPLE_ID:-}" ] && [ -n "${APPLE_APP_SPECIFIC_PASSWORD:-}" ] && [ -n "${APPLE_TEAM_ID:-}" ]; then
        NOTARY_ARGS=(--apple-id "$APPLE_ID" --password "$APPLE_APP_SPECIFIC_PASSWORD" --team-id "$APPLE_TEAM_ID")
    else
        echo -e "${RED}NOTARIZE=1 needs NOTARY_PROFILE or APPLE_ID, APPLE_APP_SPECIFIC_PASSWORD and APPLE_TEAM_ID.${NC}" >&2
        exit 1
    fi
fi

# A build that was run with sudo leaves files of root behind, and the next build as the user fails.
if [ -d "$SCRATCH" ] && [ -n "$(find "$SCRATCH" -maxdepth 3 -user root -print -quit 2>/dev/null)" ]; then
    echo -e "${RED}$SCRATCH contains files of root (an earlier build ran with sudo). Fix with:${NC}" >&2
    echo "  sudo chown -R $(id -un):$(id -gn) \"$SCRATCH\"" >&2
    exit 1
fi

if [ "${SKIP_BUILD:-0}" != "1" ]; then
    # Empty stubs for every resource that is declared in a header and not kept.
    STUBS="$RESOURCES/slim_stubs.c"
    {
        echo "// Generated by Apps/gRPCServerProxy/build.sh. Do not edit."
        echo "#include <stddef.h>"
        echo "static const unsigned char slim_empty[1] = {0};"
        for header in "$RESOURCES"/*_generated.h; do
            base="$(basename "$header" _generated.h)"
            case " $KEEP " in *" $base "*) continue ;; esac
            for name in $(sed -n 's/^extern const size_t \(.*\)_size;$/\1/p' "$header"); do
                echo "const size_t ${name}_size = 0;"
                echo "void *${name}(void) { return (void *)slim_empty; }"
            done
        done
    } > "$STUBS"

    # The packages are not fetched again: the folders of the normal build are cloned once.
    if [ ! -d "$SCRATCH/checkouts" ] && [ -d "$REPO_ROOT/.build/checkouts" ]; then
        mkdir -p "$SCRATCH"
        cp -c -R "$REPO_ROOT/.build/checkouts" "$REPO_ROOT/.build/repositories" \
            "$REPO_ROOT/.build/workspace-state.json" "$SCRATCH/"
    fi

    # SwiftPM may rewrite Package.resolved; the file is put back afterwards.
    mkdir -p "$BUILD_DIR"
    cp Package.resolved "$BUILD_DIR.Package.resolved.bak"
    trap 'cp "$BUILD_DIR.Package.resolved.bak" "$REPO_ROOT/Package.resolved"; rm -f "$BUILD_DIR.Package.resolved.bak"' EXIT

    echo -e "${YELLOW}Building release (slim resources)…${NC}"
    # The compilers put the path of every source file into the binary (assertion messages, C++ checks);
    # the paths are rewritten so that the build folder of the user does not end up in a published binary.
    REMAP=(-Xswiftc -file-prefix-map -Xswiftc "$REPO_ROOT=/draw-things-community"
        -Xcc "-ffile-prefix-map=$REPO_ROOT=/draw-things-community"
        -Xcxx "-ffile-prefix-map=$REPO_ROOT=/draw-things-community")
    DRAWTHINGS_SLIM_RESOURCES=1 swift build -c release --product "$PRODUCT" --scratch-path "$SCRATCH" "${REMAP[@]}"
fi

BIN_DIR="$(DRAWTHINGS_SLIM_RESOURCES=1 swift build -c release --scratch-path "$SCRATCH" --show-bin-path)"
SOURCE="$BIN_DIR/$PRODUCT"
if [ ! -x "$SOURCE" ]; then
    echo -e "${RED}No release binary at $SOURCE${NC}" >&2
    exit 1
fi

mkdir -p "$BUILD_DIR"
rm -f "$OUTPUT"
cp "$SOURCE" "$OUTPUT"
chmod u+w "$OUTPUT"
BEFORE=$(stat -f %z "$OUTPUT")

# Keep the unstripped binary: a crash report of the stripped one shows only addresses, and
# `atos` needs the symbols of exactly this build (they are found by the UUID of the binary).
UUID="$(dwarfdump -u "$OUTPUT" | head -1 | awk '{print $2}')"
if [ -n "$UUID" ]; then
    mkdir -p "$BUILD_DIR/symbols/$UUID"
    cp "$OUTPUT" "$BUILD_DIR/symbols/$UUID/$PRODUCT"
    echo "  symbols kept in build/symbols/$UUID (for atos)"
fi

echo -e "${YELLOW}Stripping local symbols…${NC}"
strip -x "$OUTPUT"

# Stripping invalidates the signature, and arm64 refuses to run an unsigned binary. A Developer ID
# signature with a fixed identifier is the same program in every build; an ad-hoc signature is not,
# and macOS drops the permissions granted to the old one.
if [ -n "$SIGN_ID" ] && security find-identity -v -p codesigning | grep -qF "$SIGN_ID"; then
    if [ "$RELEASE" = "1" ]; then
        echo -e "${YELLOW}Signing with Developer ID (hardened runtime)…${NC}"
        codesign --force --options runtime --sign "$SIGN_ID" --identifier "$IDENTIFIER" --timestamp "$OUTPUT"
    else
        codesign --force --sign "$SIGN_ID" --identifier "$IDENTIFIER" --timestamp=none "$OUTPUT"
    fi
    echo -e "${GREEN}Signed with $SIGN_ID as $IDENTIFIER${NC}"
else
    echo -e "${RED}No signing identity '$SIGN_ID' in the keychain.${NC}" >&2
    exit 1
fi
codesign --verify --strict "$OUTPUT"
lipo -archs "$OUTPUT" | grep -qx arm64 || { echo -e "${RED}Not an arm64-only binary: $(lipo -archs "$OUTPUT")${NC}" >&2; exit 1; }

if [ "$NOTARIZE" = "1" ]; then
    echo -e "${YELLOW}Submitting to Apple Notary Service (may take a few minutes)…${NC}"
    NOTARIZE_ZIP="$BUILD_DIR/${PRODUCT}-notarize.zip"
    rm -f "$NOTARIZE_ZIP"
    ditto -c -k "$OUTPUT" "$NOTARIZE_ZIP"
    SUBMISSION="$(xcrun notarytool submit "$NOTARIZE_ZIP" "${NOTARY_ARGS[@]}" --wait 2>&1)" || true
    echo "$SUBMISSION"
    rm -f "$NOTARIZE_ZIP"
    if ! echo "$SUBMISSION" | grep -q "status: Accepted"; then
        echo -e "${RED}ERROR: notarization was not accepted.${NC}" >&2
        exit 1
    fi
    echo -e "${GREEN}✓ Notarization accepted.${NC} (A bare executable cannot be stapled.)"
fi

AFTER=$(stat -f %z "$OUTPUT")
echo -e "${GREEN}=== Done ===${NC}"
echo "  $OUTPUT"
echo "  $((BEFORE / 1000000)) MB -> $((AFTER / 1000000)) MB"
